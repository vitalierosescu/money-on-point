function getMessage(locale: UiLocale, key: string): string | undefined {
  const parts = key.split(".")

  let current: unknown = messages[locale]
  for (const part of parts) {
    if (!current || typeof current !== "object" || !(part in current)) {
      return undefined
    }
    current = (current as Record<string, unknown>)[part]
  }

  return typeof current === "string" ? current : undefined
}

export function t(locale: UiLocale, key: string, values?: Record<string, string | number>) {
  const template = getMessage(locale, key) ?? getMessage(DEFAULT_UI_LOCALE, key) ?? key

  if (!values) {
    return template
  }

  return template.replace(/\{\{(\w+)\}\}/g, (_, token: string) => String(values[token] ?? ""))
}
